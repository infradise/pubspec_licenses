import 'dart:async';
import 'dart:convert';
import 'dart:io';

import 'license_crawler.dart';
import 'package.dart';
import 'path_utils.dart' as path;

String _sanitizeIdentifier(String name) =>
    name.replaceAll(RegExp(r'[^a-zA-Z0-9_$]'), '_');

/// Finds the project root directory by searching for `pubspec.yaml`.
///
/// Starts from [from] directory (defaults to [Directory.current]) and
/// traverses up the directory tree until a `pubspec.yaml` file is found.
Future<String> findProjectRoot({Directory? from}) async {
  var current = (from ?? Directory.current).absolute;
  while (true) {
    if (await File(path.join(current.path, 'pubspec.yaml')).exists()) {
      return current.path;
    }
    final parent = current.parent;
    if (parent.path == current.path) {
      throw StateError(
        'Could not find pubspec.yaml starting from ${(from ?? Directory.current).path}',
      );
    }
    current = parent;
  }
}

/// Renders the `oss_licenses.dart` Dart source code for [deps], matching
/// `dart_pubspec_licenses` v3.2.0 output format 1:1.
String renderDartLicensesFile(
  ProjectStructure deps, {
  List<String> ignore = const <String>[],
}) {
  final sb = StringBuffer();
  final ignoredSet = ignore.toSet();

  String toQuotedString(String s) {
    var escaped = s
        .replaceAll(r'\', r'\\')
        .replaceAll(r'$', r'\$')
        .replaceAll('\r', r'\r')
        .replaceAll('\x00', r'\x00');
    final quoteCount = "'".allMatches(s).length;
    final doubleQuoteCount = '"'.allMatches(s).length;
    final quote = quoteCount > doubleQuoteCount ? '"' : "'";
    if (!escaped.contains('\n')) {
      return quote + escaped.replaceAll(quote, '\\$quote') + quote;
    }
    final q3 = quote * 3;
    escaped = escaped.replaceAll(q3, '\\$quote' * 3);
    if (escaped.endsWith(quote)) {
      escaped = '${escaped.substring(0, escaped.length - 1)}\\$quote';
    }
    return '$q3$escaped$q3';
  }

  final effectiveRootPackage = ignoredSet.contains(deps.package.name)
      ? Package(
          name: deps.package.name,
          description: '',
          authors: const <String>[],
          isMarkdown: false,
          isSdk: deps.package.isSdk,
          dependencies: deps.package.dependencies,
          devDependencies: deps.package.devDependencies,
        )
      : deps.package;

  final allRenderedPackages = <Package>[
    ...deps.allDependencies,
    effectiveRootPackage,
  ];

  final usedIdentifiers = <String>{};
  final packageIdentMap = <String, String>{};
  for (final pkg in allRenderedPackages) {
    if (packageIdentMap.containsKey(pkg.name)) continue;
    final base = '_${_sanitizeIdentifier(pkg.name)}';
    var candidate = base;
    var suffix = 2;
    while (!usedIdentifiers.add(candidate)) {
      candidate = '${base}_$suffix';
      suffix++;
    }
    packageIdentMap[pkg.name] = candidate;
  }

  String identOf(String pkgName) =>
      packageIdentMap[pkgName] ?? '_${_sanitizeIdentifier(pkgName)}';

  void writeIfNotNull(String name, Object? obj) {
    if (obj == null) return;
    if (obj is List) {
      sb.write('    $name: [');
      for (var i = 0; i < obj.length; i++) {
        if (i > 0) sb.write(', ');
        sb.write(toQuotedString(obj[i].toString()));
      }
      sb.writeln('],');
      return;
    }
    if (obj is! String) {
      sb.writeln('    $name: $obj,');
      return;
    }
    sb.writeln('    $name: ${toQuotedString(obj)},');
  }

  for (final l in allRenderedPackages) {
    sb.writeln('/// ${l.name} ${l.version}');
    sb.writeln('const ${identOf(l.name)} = Package(');
    writeIfNotNull('name', l.name);
    writeIfNotNull('description', l.description);
    writeIfNotNull('homepage', l.homepage);
    writeIfNotNull('repository', l.repository);
    writeIfNotNull('authors', l.authors);
    writeIfNotNull('version', l.version);
    writeIfNotNull('spdxIdentifiers', l.spdxIdentifiers);
    writeIfNotNull('isMarkdown', l.isMarkdown);
    writeIfNotNull('isSdk', l.isSdk);
    sb.writeln(
      '    dependencies: [${l.dependencies.map((d) => 'PackageRef(${toQuotedString(d.name)})').join(', ')}],',
    );
    sb.writeln(
      '    devDependencies: [${l.devDependencies.map((d) => 'PackageRef(${toQuotedString(d.name)})').join(', ')}],',
    );
    writeIfNotNull('license', l.license);
    sb.writeln('  );');
    sb.writeln('');
  }

  return '''
// dart format off
// cSpell:disable
// ignore_for_file: always_put_required_named_parameters_first
// ignore_for_file: constant_identifier_names
// ignore_for_file: sort_constructors_first

// This code was generated by pubspec_licenses
// https://pub.dev/packages/pubspec_licenses

/// This package.
const thisPackage = ${identOf(effectiveRootPackage.name)};

/// All dependencies including transitive dependencies.
const allDependencies = <Package>[
${deps.allDependencies.map((d) => '  ${identOf(d.name)}').join(',\n')}
];

/// Direct `dependencies`.
const dependencies = <Package>[
${effectiveRootPackage.dependencies.map((d) => '  ${identOf(d.name)}').join(',\n')}
];

/// Direct `dev_dependencies`.
const devDependencies = <Package>[
${effectiveRootPackage.devDependencies.map((d) => '  ${identOf(d.name)}').join(',\n')}
];

/// Package license definition.
class Package {
  /// Package name
  final String name;
  /// Description
  final String description;
  /// Authors
  final List<String> authors;
  /// Whether the license is in markdown format or not (plain text).
  final bool isMarkdown;
  /// Whether the package is included in the SDK or not.
  final bool isSdk;
  /// Direct dependencies
  final List<PackageRef> dependencies;
  /// Direct devDependencies
  final List<PackageRef> devDependencies;
  /// Website URL
  final String? homepage;
  /// Repository URL
  final String? repository;
  /// Version
  final String? version;
  /// License
  final String? license;
  /// The [SPDX](https://spdx.org/licenses/) license identifiers, if detected.
  final List<String> spdxIdentifiers;

  const Package({
    required this.name,
    required this.description,
    required this.authors,
    required this.isMarkdown,
    required this.isSdk,
    required this.dependencies,
    required this.devDependencies,
    this.homepage,
    this.repository,
    this.version,
    this.license,
    this.spdxIdentifiers = const [],
  });
}

class PackageRef {
  final String name;

  const PackageRef(this.name);

  Package resolve() => allDependencies.firstWhere((d) => d.name == name);
}

$sb''';
}

/// Generates license information file or stdout output from CLI [args].
///
/// When invoked without `--output` (`-o`), `--json` (`-j`), or `--summary`
/// (`-s`), defaults to generating `lib/oss_licenses.dart` in the project root
/// (or `oss_licenses.dart` if `lib/` does not exist), matching
/// `dart_pubspec_licenses` v3.2.0 behavior.
///
/// Returns an exit code: `0` for success, non-zero for error conditions.
Future<int> generate(List<String> args) async {
  String? pubspecLockPath;
  String? projectRoot;
  String? flutterDirPath;
  String? pubCacheDirPath;
  String? outputPath;
  var jsonOutput = false;
  var dartOutput = false;
  var summaryOutput = false;
  var generateDevDependencies = true;
  var splitSdkLicenses = false;
  var showHelp = false;
  final ignore = <String>[];

  for (var i = 0; i < args.length; i++) {
    final arg = args[i];
    if (arg == '--help' || arg == '-h') {
      showHelp = true;
    } else if (arg == '--json' || arg == '-j') {
      jsonOutput = true;
    } else if (arg == '--dart') {
      dartOutput = true;
    } else if (arg == '--summary' || arg == '-s') {
      summaryOutput = true;
    } else if (arg == '--no-dev-dependencies' ||
        arg == '--no-generate-dev-dependencies') {
      generateDevDependencies = false;
    } else if (arg == '--dev-dependencies' ||
        arg == '--generate-dev-dependencies') {
      generateDevDependencies = true;
    } else if (arg == '--split-sdk-licenses') {
      splitSdkLicenses = true;
    } else if (arg == '--pubspec-lock' && i + 1 < args.length) {
      pubspecLockPath = args[++i];
    } else if (arg.startsWith('--pubspec-lock=')) {
      pubspecLockPath = arg.substring('--pubspec-lock='.length);
    } else if ((arg == '--flutter-dir' || arg == '--flutter-root') &&
        i + 1 < args.length) {
      flutterDirPath = args[++i];
    } else if (arg.startsWith('--flutter-dir=')) {
      flutterDirPath = arg.substring('--flutter-dir='.length);
    } else if (arg.startsWith('--flutter-root=')) {
      flutterDirPath = arg.substring('--flutter-root='.length);
    } else if (arg == '--pub-cache-dir' && i + 1 < args.length) {
      pubCacheDirPath = args[++i];
    } else if (arg.startsWith('--pub-cache-dir=')) {
      pubCacheDirPath = arg.substring('--pub-cache-dir='.length);
    } else if ((arg == '--project-root' || arg == '-p') &&
        i + 1 < args.length) {
      projectRoot = args[++i];
    } else if (arg.startsWith('--project-root=')) {
      projectRoot = arg.substring('--project-root='.length);
    } else if ((arg == '--output' || arg == '-o') && i + 1 < args.length) {
      outputPath = args[++i];
    } else if (arg.startsWith('--output=')) {
      outputPath = arg.substring('--output='.length);
    } else if ((arg == '--ignore' || arg == '-i') && i + 1 < args.length) {
      ignore.addAll(
        args[++i].split(',').map((s) => s.trim()).where((s) => s.isNotEmpty),
      );
    } else if (arg.startsWith('--ignore=')) {
      ignore.addAll(
        arg
            .substring('--ignore='.length)
            .split(',')
            .map((s) => s.trim())
            .where((s) => s.isNotEmpty),
      );
    } else {
      stderr.writeln('WARNING: unknown or extra parameter given: $arg');
      printUsage();
      exitCode = 3;
      return 3;
    }
  }

  if (showHelp) {
    printUsage();
    return 0;
  }

  try {
    String effectiveProjectRoot;
    String effectiveLockPath;
    String? effectiveYamlPath;
    if (pubspecLockPath != null && pubspecLockPath.isNotEmpty) {
      effectiveLockPath = pubspecLockPath;
      effectiveProjectRoot = projectRoot ?? path.dirname(pubspecLockPath);
      final candidateYaml = path.join(effectiveProjectRoot, 'pubspec.yaml');
      if (File(candidateYaml).existsSync()) {
        effectiveYamlPath = candidateYaml;
      }
    } else if (projectRoot != null && projectRoot.isNotEmpty) {
      effectiveProjectRoot = projectRoot;
      effectiveLockPath = findPubspecLockFromDirectory(Directory(projectRoot));
      final candidateYaml = path.join(projectRoot, 'pubspec.yaml');
      if (File(candidateYaml).existsSync()) {
        effectiveYamlPath = candidateYaml;
      }
    } else {
      effectiveProjectRoot = await findProjectRoot();
      effectiveLockPath = findPubspecLockFromDirectory(
        Directory(effectiveProjectRoot),
      );
      effectiveYamlPath = path.join(effectiveProjectRoot, 'pubspec.yaml');
    }

    // When neither -o/--output, -j/--json, nor -s/--summary is provided,
    // default to generating lib/oss_licenses.dart (or oss_licenses.dart if
    // lib/ does not exist), matching dart_pubspec_licenses v3.2.0.
    if (outputPath == null && !jsonOutput && !summaryOutput) {
      final libDir = Directory(path.join(effectiveProjectRoot, 'lib'));
      outputPath = libDir.existsSync()
          ? path.join(effectiveProjectRoot, 'lib', 'oss_licenses.dart')
          : path.join(effectiveProjectRoot, 'oss_licenses.dart');
      dartOutput = true;
    }

    final structure = await listDependencies(
      pubspecLockPath: effectiveLockPath,
      pubspecYamlPath: effectiveYamlPath,
      flutterDirPath: flutterDirPath,
      pubCacheDirPath: pubCacheDirPath,
      ignore: ignore,
      generateDevDependencies: generateDevDependencies,
      splitSdkLicenses: splitSdkLicenses,
    );

    final directDeps =
        structure.package.dependencies.map((p) => p.name).toSet();
    final isJsonMode = jsonOutput ||
        (outputPath != null &&
            outputPath != '-' &&
            path.extension(outputPath).toLowerCase() == '.json');
    final isSummaryMode = summaryOutput && !isJsonMode && !dartOutput;

    String rendered;
    if (isJsonMode) {
      final list = <Package>[
        ...structure.allDependencies,
        if (!ignore.contains(structure.package.name)) structure.package,
      ];
      rendered = const JsonEncoder.withIndent('  ').convert(
        list
            .map(
              (pkg) => pkg.toJson(
                isDirectDependency: directDeps.contains(pkg.name),
              ),
            )
            .toList(),
      );
    } else if (isSummaryMode) {
      final buffer = StringBuffer();
      buffer.writeln(
        'Project: ${structure.package.name} (${structure.package.version ?? "unversioned"})',
      );
      buffer.writeln(
        'Dependencies found: ${structure.allDependencies.length}',
      );
      for (final pkg in structure.allDependencies) {
        final spdx = pkg.spdxIdentifiers.isEmpty
            ? 'UNKNOWN'
            : pkg.spdxIdentifiers.join(', ');
        buffer.writeln(
          '  - ${pkg.name} ${pkg.version ?? ""} [$spdx]${pkg.isDirectDependency ? " (direct)" : ""}',
        );
      }
      rendered = buffer.toString().trimRight();
    } else {
      rendered = renderDartLicensesFile(structure, ignore: ignore);
    }

    if (outputPath == null || outputPath == '-') {
      stdout.writeln(rendered);
    } else {
      final outFile = File(outputPath);
      if (!outFile.parent.existsSync()) {
        outFile.parent.createSync(recursive: true);
      }
      await outFile.writeAsString(
        rendered.endsWith('\n') ? rendered : '$rendered\n',
      );
    }
    return 0;
  } catch (e) {
    stderr.writeln('Error: $e');
    exitCode = 4;
    return 4;
  }
}

/// Prints CLI usage instructions to `stdout`.
void printUsage() {
  stdout.writeln(
    'Usage: pubspec_licenses [options]\n\n'
    'Options:\n'
    '  --pubspec-lock <path>    Path to pubspec.lock (defaults to ./pubspec.lock)\n'
    '  --flutter-dir <path>     Path to Flutter SDK root directory\n'
    '  --pub-cache-dir <path>   Path to Pub cache directory\n'
    '  -p, --project-root <dir> Project root directory containing pubspec.lock\n'
    '  -o, --output <path>      Output file path (defaults to lib/oss_licenses.dart;\n'
    '                           use - for stdout)\n'
    '  -i, --ignore <pkgs>      Comma-separated list of package names to ignore\n'
    '  -j, --json               Output license metadata in JSON format\n'
    '  --dart                   Output Dart source code (oss_licenses.dart format)\n'
    '  -s, --summary            Print human-readable dependency license summary\n'
    '  --no-dev-dependencies    Exclude dev_dependencies from license resolution\n'
    '  --split-sdk-licenses     Split sky_engine bundled licenses into sub-packages\n'
    '  -h, --help               Show this usage information',
  );
}
